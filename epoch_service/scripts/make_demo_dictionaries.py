def build(genre, groups):
    markers, seen = {}, set()
    for era, line in zip(ERAS, groups):
        for i, w in enumerate(line.split()):
            if w in seen:
                continue
            seen.add(w)
            markers[w] = {"era": era, "log_ratio": round(4.5 - 0.15 * i, 2), "G2": None, "era_share": None}
    return {"genre": genre, "unit": "form", "demo": True, "eras": ERAS,
            "normalization": "нижний регистр, ё->е",
            "note": "Демонстрационный словарь: слова подобраны вручную, log_ratio условный.",
            "markers": markers}


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dictionaries")
    for genre, groups in WORDS.items():
        path = os.path.join(out, f"dict_{genre}_form.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(build(genre, groups), f, ensure_ascii=False, indent=1)
        print(path)
