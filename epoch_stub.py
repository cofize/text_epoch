"""
ЗАГЛУШКА модели датировки текста.

Единственная точка входа — predict(text). Когда будет готова настоящая модель,
в nlp.py меняется одна строка импорта. Формат ответа менять нельзя:
он зафиксирован в API.md и API_CONTRACT.md.

Это НЕ обученная модель, а словарь: заглушка ищет в тексте слова из заранее
составленного списка (архаизмы, этикет, реалии, советизмы, современная лексика)
и считает по ним оценки трёх периодов. Если в тексте нет ни одного слова
из списка, она отвечает «не удалось определить». Нужна, чтобы сайт работал
до готовности настоящей модели; в ответе помечена полем "stub": true.
"""
import math
import re

PERIODS = {
    "xviii": "XVIII век",
    "xix": "XIX век",
    "xx": "XX век и позже",
}
ORDER = ["xviii", "xix", "xx"]

# (регулярное выражение, вид признака, веса по периодам, пояснение)
# Веса — «сколько очков даёт один такой признак» каждому периоду.
#
# Тексты из корпусов и библиотек приведены к современной орфографии,
# поэтому правила опираются на ЛЕКСИКУ, а не на написание.
def W(a, b, c):
    return {"xviii": a, "xix": b, "xx": c}

_RULES = [
    # --- XVIII век: архаичные служебные слова, которые не восстановишь нормализацией ---
    (r"\b(дабы|аки|яко|паче|зело|сиречь|понеже|поелику|дондеже|паки|толико|днесь|"
     r"оный|оная|оное|оные|оного|оной|оных|оным|оными|оному)\b", "архаизм", W(2.2, 0.5, 0.0),
     "служебное слово или местоимение XVIII века"),
    (r"\b(сей|сия|сие|сии|сего|сему|сим|сих|сколь|ибо|ныне|буде|нежели|отнюдь|"
     r"всенепременно|невозбранно)\b", "книжное слово", W(1.4, 1.0, 0.1),
     "книжное слово, уходящее из речи к XX веку"),
    (r"\b(указ(?:а|у|ом|е|ы|ов|ам|ами|ах)?|сенат\w*|ассамбле\w+|государын\w+|императриц\w+|"
     r"самодержиц\w+|фельдмаршал\w*|рекрут\w*|бригадир\w*|пиит\w*|россиян\w+|"
     r"добродетел\w+|фортун\w+|монарх\w*|ея|стихотворец|стихотворц\w+|"
     r"экзерциц\w+|кунсткамер\w+|ассигнаци\w+)\b", "реалия", W(1.7, 0.6, 0.0),
     "слово или реалия, характерные для XVIII века"),
    # --- XIX век: этикет и речь ---
    (r"\b\w+-с\b", "речевой этикет", W(0.0, 2.0, 0.1),
     "частица «-с» (слово-ер): «извольте-с»"),
    (r"\b(ваше (?:благородие|высокоблагородие|превосходительство|сиятельство|высочество)|"
     r"милостив\w+ государ\w+|сударын\w+|извол(?:ьте|ите|ил|ила|или|ь)|соизвол\w+|"
     r"пожалуйте|помилуйте|сделайте одолжение|премного|покорнейше)\b", "речевой этикет",
     W(0.2, 2.0, 0.1), "оборот вежливости эпохи сословного общества"),
    (r"\b(ежели|эдак\w*|этак\w*|эдакий|этакий|тотчас|давеча|нынче|сызнова|намедни|авось|"
     r"чрезвычайно|пренепременно|ничтоже)\b", "разговорное слово", W(0.3, 1.5, 0.2),
     "разговорная или книжная форма, характерная для XIX века"),
    # --- XIX век: реалии ---
    (r"\b(помещик\w*|барин\w*|барын\w+|барышн\w+|лакей\w*|дворов(?:ый|ые|ого|ых|ым)|"
     r"крепостн\w+|уездн\w+|губернск\w+|губерни\w+|городничи\w+|исправник\w*|"
     r"становой|станционн\w+ смотрител\w+|ямщик\w*|тройк\w+|перекладн\w+|дилижанс\w*|"
     r"чугунк\w+|извозчик\w*|мазурк\w+|кадрил\w+|кринолин\w*|лорнет\w*|сюртук\w*|"
     r"бекеш\w+|нигилист\w*|славянофил\w*|западник\w*|гимназист\w*|экипаж\w*|"
     r"вояж\w*|имени[ея]|барщин\w+|оброк\w*)\b", "реалия", W(0.2, 1.7, 0.2),
     "реалия дореволюционной России"),
    (r"\b(железн\w+ дорог\w+|телеграф\w*|пароход\w*|паровоз\w*|керосин\w*)\b", "реалия",
     W(0.0, 1.4, 0.6), "техника XIX века"),
    # --- XX век: советская эпоха ---
    (r"\b(товарищ\w*|колхоз\w*|совхоз\w*|комсомол\w*|пионер\w*|большевик\w*|"
     r"пролетариат\w*|пятилетк\w+|партком\w*|совнарком\w*|райком\w*|стахановец|"
     r"стахановц\w+|ударник\w*|субботник\w*|октябр[её]н\w*|комиссар\w*|чекист\w*|"
     r"нквд|гулаг\w*|красноармей\w+|рабфак\w*|нэп\w*|парторг\w*|трудодн\w+|"
     r"советск\w+|совет(?:ов|ам|ах)|коммунальн\w+|врагов? народа)\b", "советизм",
     W(0.0, 0.1, 2.5), "советская реалия"),
    (r"\b(трактор\w*|радио|телефон\w*|самол[её]т\w*|кино|метро|танк(?:а|у|ом|е|и|ов)?|"
     r"телевизор\w*|институт\w*|завод(?:а|у|ом|е|ы|ов|ах)?|фронт(?:а|у|ом|е|ов)?|"
     r"эвакуаци\w+|автомобил\w+|автобус\w*|трамва\w+|троллейбус\w*|холодильник\w*|"
     r"пылесос\w*|хрущ[её]вк\w+|магнитофон\w*)\b", "реалия",
     W(0.0, 0.1, 1.6), "понятие, распространившееся в XX веке"),
    # --- конец XX — XXI век ---
    (r"\b(компьютер\w*|интернет\w*|смартфон\w*|сайт\w*|онлайн|видео|email|имейл\w*|"
     r"гаджет\w*|блог\w*|лайк\w*|соцсет\w+|окей|прикольн\w+|чувак\w*|тусовк\w+|"
     r"перестройк\w+|приватизаци\w+|кооператив\w*)\b", "современная лексика",
     W(0.0, 0.0, 2.3), "лексика конца XX — XXI века"),
]
_COMPILED = [(re.compile(p, re.IGNORECASE), k, w, n) for p, k, w, n in _RULES]


def _find_markers(text: str) -> list[dict]:
    found = []
    for rx, kind, weights, note in _COMPILED:
        for m in rx.finditer(text):
            if not m.group(0).strip():
                continue
            found.append({
                "text": m.group(0),
                "start": m.start(),
                "end": m.end(),
                "kind": kind,
                "weights": weights,
                "note": note,
            })
    # Убираем пересечения: длинные и более весомые признаки выигрывают.
    found.sort(key=lambda x: (-(x["end"] - x["start"]), x["start"]))
    kept, taken = [], []
    for f in found:
        if any(f["start"] < e and s < f["end"] for s, e in taken):
            continue
        kept.append(f)
        taken.append((f["start"], f["end"]))
    kept.sort(key=lambda x: x["start"])
    return kept


def predict(text: str) -> dict:
    """Вернуть словарь строго по контракту: period, score, all_scores, dated_markers."""
    markers = _find_markers(text)

    raw = {p: 0.0 for p in ORDER}
    for m in markers:
        for p in ORDER:
            raw[p] += m["weights"][p]

    # softmax: без признаков получается ровное распределение, уверенность ~0.33
    exps = {p: math.exp(0.45 * raw[p]) for p in ORDER}
    total = sum(exps.values())
    all_scores = {p: round(exps[p] / total, 3) for p in ORDER}
    best = max(ORDER, key=lambda p: all_scores[p])

    dated = []
    for m in markers:
        # к какому периоду признак «тянет» сильнее всего
        owner = max(ORDER, key=lambda p: m["weights"][p])
        dated.append({
            "text": m["text"],
            "start": m["start"],
            "end": m["end"],
            "period": owner,
            "kind": m["kind"],
            "note": m["note"],
        })

    return {
        "period": best,
        "period_label": PERIODS[best],
        "score": all_scores[best],
        # True, если признаков мало и вердикт нельзя считать надёжным
        "stub": True,   # признак заглушки; настоящая модель это поле не возвращает
        "uncertain": len(markers) == 0 or all_scores[best] < 0.45,
        "all_scores": all_scores,
        "dated_markers": dated,
    }
